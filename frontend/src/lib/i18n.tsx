const I18nContext = createContext<{
  language: Language;
  setLanguage: (language: Language) => void;
  t: (key: string, values?: Record<string, string | number>) => string;
}>({
  language: "en",
  setLanguage: () => undefined,
  t: (key) => key,
});

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [language, setLanguageState] = useState<Language>(() => (localStorage.getItem("language") === "ar" ? "ar" : "en"));

  useEffect(() => {
    localStorage.setItem("language", language);
    document.documentElement.lang = language;
    document.documentElement.dir = language === "ar" ? "rtl" : "ltr";
  }, [language]);

  const value = useMemo(() => {
    const t = (key: string, values: Record<string, string | number> = {}) => {
      let text = dictionaries[language][key] ?? dictionaries.en[key] ?? key;
      Object.entries(values).forEach(([name, replacement]) => {
        text = text.split(`{${name}}`).join(String(replacement));
      });
      return text;
    };
    return { language, setLanguage: setLanguageState, t };
  }, [language]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  return useContext(I18nContext);
}
